import type { Language } from "../lib/i18n";
export type Page = "overview" | "new-record" | "handover" | "history";
export type Theme = "light" | "dark";
export type Kind = "EVENT" | "NOTE" | "VALVE" | "ATTENTION" | "TASK";
export type Priority = "NORMAL" | "HIGH";
export type WorkStatus = "OPEN" | "IN_PROGRESS" | "WAITING";
export type EquipmentStatus = "UNKNOWN" | "ACTIVE" | "INACTIVE" | "MAINTENANCE";
export type Message = { key?: string; text?: string; api?: string; error?: boolean };
export type Person = { id: number; name: string };
export type User = Person & { email?: string; role: "MANAGER" | "WORKER" | "SUPERVISOR" };
export type Shift = { id: number; startTime: string; endTime?: string | null; shiftDate?: string; scheduledStart?: string; scheduledEnd?: string; status?: string; user: Person };
export type Equipment = { code: string; status: EquipmentStatus; note?: string; version: number; updatedAt?: string | null; updatedBy?: Person | null };
export type WorkFields = { workStatus: WorkStatus; responsibleTeam: string; nextStep: string };
export type Entry = Partial<WorkFields> & {
  id: number; kind: Kind; priority: Priority; title: string; description?: string; createdAt?: string;
  equipmentCode?: string | null; author?: Person; shiftId?: number | null; closedAt?: string | null; closedBy?: Person | null;
  closeNote?: string; photos?: Array<{ id: string }>; workVersion?: number;
  updates?: Progress[]; _count?: { updates: number };
};
export type Progress = { id: number; body: string; createdAt: string; author: Person };
export type WorkChange = WorkFields & { id: number; version: number; createdAt: string; author: Person };
export type PageResult<T> = { items: T[]; page: number; total: number; pageSize: number };
export type ChangeType = "NEW_ENTRY" | "CLOSED_ENTRY" | "PROGRESS" | "EQUIPMENT" | "WORK_DETAILS";
export type Change = { type: ChangeType; id: number; entryId: number | null; title: string; body?: string; kind?: Kind; equipmentCode?: string; fromStatus?: string; toStatus?: string; actorName?: string; createdAt: string; workDetails?: WorkFields };
export type Summary = {
  revision: number; equipment: Equipment[]; counts: { total: number; important: number; VALVE: number; TASK: number; ATTENTION: number };
  openItems?: Entry[]; important: Entry[]; recent: Entry[]; tasks?: Entry[]; valves?: Entry[]; attention?: Entry[];
  activeShiftId: number | null; receipt: { revision: number; readAt: string } | null;
  changes?: { shiftDate: string; scheduledStart: string; scheduledEnd: string; counts: Record<ChangeType, number>; total: number; items: Change[] };
};
export type EntryDraft = WorkFields & { kind: Kind; priority: Priority; equipmentCode: string; title: string; description: string };
export type PhotoSelection = { file: File; url: string };
export type NoteDraft = { id: number; title: string; body: string; requestId: string };
export type WorkDraft = WorkFields & { id: number; title: string; version: number };
export type ActiveEntry = { id: number; title: string; readOnly: boolean };
export type NotesState = { active: ActiveEntry | null; data: (PageResult<Progress> & { entry: Entry; canWrite: boolean }) | null; text: string; hasDraft: boolean; loading: boolean; busy: boolean; message: Message | null };
export type WorkState = { active: ActiveEntry | null; data: (PageResult<WorkChange> & { entry: Entry; canWrite: boolean }) | null; fields: Omit<WorkFields, "workStatus"> & { workStatus: WorkStatus | "CLOSED" }; hasDraft: boolean; loading: boolean; busy: boolean; message: Message | null };
export type Analysis = { equipment: string; category: string; kind: Kind; priority: Priority | "UNKNOWN"; rationale: string; uncertainty: string; evidence: string[]; questions: string[] };
export type AiState = {
  open: boolean; enabled: boolean; available: boolean; busy: boolean; result: Analysis | null; message: Message | null;
  record: string; recordTitle: string; text: string; bubbles: Array<{ id: number; role: "user" | "assistant"; text: string }>;
  source: { draft: { title: string; description: string; language: Language }; description: string; title: string } | null;
  selections: { text: boolean; unit: boolean; kind: boolean; priority: boolean };
};
export type Observation = { type: "entry"; item: Entry } | { type: "change"; item: Change };
export type Connection = { browserOnline: boolean; reachable: boolean | null; failures: string[]; lastResponse: string | null; busy: boolean };
export type AppState = {
  language: Language; theme: Theme; themePreference: Theme | null; user: User | null; page: Page; navigationVersion: number;
  authBusy: boolean; authMessage: Message | null; authReset: number; dashboardMessage: Message | null;
  current: Shift | null | undefined; currentStale: boolean; schedule: { date: string; slot: string }; shiftBusy: boolean;
  summary: Summary | null; summaryStale: boolean; checkedAt: string | null; summaryBusy: boolean;
  board: PageResult<Entry>; boardFilters: string; boardFilterDraft: { kind: string; equipment: string; priority: string };
  operations: PageResult<Entry>; operationFilters: string; operationFilterDraft: Record<string, string>; operationsBusy: boolean;
  shifts: PageResult<Shift>; shiftFilters: string; shiftFilterDraft: { from: string; to: string; scope: string }; shiftsLoading: boolean; shiftsFailed: boolean; exporting: boolean;
  entry: EntryDraft; photos: PhotoSelection[]; entrySending: boolean; entryMessage: Message | null; entryReset: number; entryFocus: number;
  equipmentDialog: { item: Equipment; status: EquipmentStatus; note: string; busy: boolean; message: Message | null } | null;
  closeDialog: { id: number; title: string; note: string; busy: boolean; message: Message | null } | null;
  observation: Observation | null; photoUrl: string | null;
  notes: NotesState; work: WorkState; ai: AiState; connection: Connection;
};
